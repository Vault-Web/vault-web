-- PostgreSQL schema for new installations, before the chat deletion flag.
create sequence refresh_token_seq start with 1 increment by 50;

create table chat_message (
    delivered_at timestamp(6) with time zone,
    group_id bigint,
    id bigint generated by default as identity,
    poll_id bigint unique,
    private_chat_id bigint,
    read_at timestamp(6) with time zone,
    sender_id bigint not null,
    timestamp timestamp(6) with time zone,
    client_message_id varchar(36),
    sender_device_id varchar(64),
    e2ee_payload TEXT,
    message_type varchar(255) check ((message_type in ('TEXT','POLL'))),
    status varchar(255) check ((status in ('SENT','DELIVERED','READ'))),
    primary key (id)
);

create table device (
    created_at timestamp(6) with time zone,
    id bigint generated by default as identity,
    last_seen timestamp(6) with time zone,
    user_id bigint not null,
    device_id varchar(64) not null unique,
    public_key TEXT not null,
    primary key (id)
);

create table group_entity (
    is_public boolean,
    created_at timestamp(6) with time zone,
    created_by_id bigint,
    id bigint generated by default as identity,
    description varchar(255),
    name varchar(255),
    primary key (id)
);

create table group_members (
    group_id bigint,
    id bigint generated by default as identity,
    user_id bigint,
    role varchar(255) check ((role in ('USER','ADMIN'))),
    primary key (id)
);

create table poll_options (
    id bigint generated by default as identity,
    poll_id bigint not null,
    text varchar(255),
    primary key (id)
);

create table poll_votes (
    id bigint generated by default as identity,
    poll_id bigint not null,
    poll_option_id bigint not null,
    user_id bigint not null,
    primary key (id),
    constraint uk_poll_votes_poll_user unique (poll_id, user_id)
);

create table polls (
    is_anonymous boolean not null,
    author_id bigint not null,
    created_at timestamp(6) with time zone,
    deadline timestamp(6) with time zone,
    group_id bigint,
    id bigint generated by default as identity,
    private_chat_id bigint,
    question varchar(255),
    primary key (id)
);

create table private_chat (
    id bigint generated by default as identity,
    user1_id bigint,
    user2_id bigint,
    primary key (id)
);

create table refresh_token (
    revoked boolean not null,
    created_at timestamp(6) with time zone not null,
    expires_at timestamp(6) with time zone not null,
    id bigint not null,
    user_id bigint not null,
    token_hash varchar(255) not null,
    token_id varchar(255) not null unique,
    primary key (id)
);

create table security_event (
    id bigint generated by default as identity,
    timestamp timestamp(6) with time zone,
    user_id bigint,
    device_id varchar(255),
    event_type varchar(255) check ((event_type in ('LOGIN','LOGOUT','REGISTER','TOKEN_REFRESH','PASSWORD_CHANGE','NEW_DEVICE_DETECTED','VAULT_UNLOCKED','VAULT_LOCKED','TOKEN_REPLAY_DETECTED'))),
    ip_address varchar(255),
    location varchar(255),
    status varchar(255),
    user_agent TEXT,
    username varchar(255),
    primary key (id)
);

create table vault_user (
    id bigint generated by default as identity,
    password varchar(255),
    profile_picture varchar(255),
    username varchar(255),
    primary key (id)
);

create table workspace_activity (
    created_at timestamp(6) with time zone not null,
    id bigint generated by default as identity,
    project_id bigint not null,
    event varchar(50) not null,
    actor varchar(255) not null,
    primary key (id)
);

create table workspace_member (
    id bigint generated by default as identity,
    project_id bigint not null,
    user_id bigint not null,
    role varchar(10) not null check ((role in ('OWNER','ADMIN','MEMBER'))),
    primary key (id),
    unique (project_id, user_id)
);

create table workspace_project (
    archived boolean not null,
    created_at timestamp(6) with time zone not null,
    discussion_group_id bigint,
    id bigint generated by default as identity,
    name varchar(120) not null,
    description varchar(2000) not null,
    primary key (id)
);

create table workspace_resource (
    folder boolean not null,
    id bigint generated by default as identity,
    owner_id bigint not null,
    project_id bigint not null,
    path varchar(1024) not null,
    primary key (id)
);

