CREATE TABLE personal_access_token (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  public_id varchar(16) NOT NULL,
  user_id bigint NOT NULL REFERENCES vault_user(id),
  name varchar(64) NOT NULL,
  token_hash varchar(64) NOT NULL,
  audience varchar(32) NOT NULL,
  created_at timestamptz NOT NULL,
  expires_at timestamptz NOT NULL,
  last_used_at timestamptz,
  revoked_at timestamptz,
  CONSTRAINT uk_pat_public_id UNIQUE (public_id)
);
CREATE TABLE personal_access_token_scope (
  token_id bigint NOT NULL REFERENCES personal_access_token(id),
  scope varchar(32) NOT NULL,
  PRIMARY KEY (token_id, scope)
);
CREATE INDEX idx_pat_user ON personal_access_token(user_id);
