-- Additive, manually applied before enabling project workspaces. No old tables are changed.
BEGIN;
CREATE TABLE workspace_project (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(120) NOT NULL,
  description varchar(2000) NOT NULL,
  archived boolean NOT NULL,
  created_at timestamptz NOT NULL,
  discussion_group_id bigint
);
CREATE TABLE workspace_member (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id bigint NOT NULL REFERENCES workspace_project(id),
  user_id bigint NOT NULL REFERENCES vault_user(id),
  role varchar(10) NOT NULL,
  UNIQUE (project_id, user_id)
);
CREATE TABLE workspace_resource (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id bigint NOT NULL REFERENCES workspace_project(id),
  owner_id bigint NOT NULL REFERENCES vault_user(id),
  path varchar(1024) NOT NULL,
  folder boolean NOT NULL
);
CREATE TABLE workspace_activity (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id bigint NOT NULL REFERENCES workspace_project(id),
  event varchar(50) NOT NULL,
  actor varchar(255) NOT NULL,
  created_at timestamptz NOT NULL
);
CREATE INDEX workspace_member_user ON workspace_member(user_id);
CREATE INDEX workspace_activity_project ON workspace_activity(project_id, id DESC);
COMMIT;
